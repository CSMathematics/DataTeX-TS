#!/usr/bin/env node

import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import tailwindcss from "@tailwindcss/vite";
import { build as viteBuild } from "vite";

import {
  STOICHEIA_SCOPE,
  auditCss,
  scopeCss,
} from "./lib/scope-stoicheia-css.mjs";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "..");
const require = createRequire(import.meta.url);
const tailwindVersion = require("tailwindcss/package.json").version;
const featureRoot = path.join(repositoryRoot, "src/features/stoicheia");
const sourcePath = path.join(featureRoot, "App.css");
const outputPath = path.join(
  featureRoot,
  "styles/stoicheia.embedded.css",
);
const generatedHeader = [
  "/*",
  " * Generated by scripts/build-stoicheia-css.mjs.",
  " * Source: src/features/stoicheia/App.css",
  ` * Tailwind compiler: tailwindcss@${tailwindVersion}`,
  " * Candidate tree: src/features/stoicheia/**",
  " * Lock inputs: package.json, pnpm-lock.yaml",
  ` * Boundary: ${STOICHEIA_SCOPE}`,
  " * Global namespaces: stoicheia-* / --stoicheia-tw-*",
  " * Do not edit this file directly.",
  " */",
  "",
].join("\n");

function parseArguments(argv) {
  let check = false;

  for (const argument of argv) {
    if (argument === "--check") {
      check = true;
      continue;
    }

    if (argument === "--help" || argument === "-h") {
      process.stdout.write(
        [
          "Usage:",
          "  node scripts/build-stoicheia-css.mjs",
          "  node scripts/build-stoicheia-css.mjs --check",
          "",
          "Compiles the copied Stoicheia stylesheet with Tailwind v4,",
          `then constrains every selector to ${STOICHEIA_SCOPE}.`,
          "",
        ].join("\n"),
      );
      process.exit(0);
    }

    throw new Error(`Unknown argument: ${argument}`);
  }

  return { check };
}

function normalizeBuildOutputs(result) {
  const builds = Array.isArray(result) ? result : [result];
  return builds.flatMap((buildResult) => buildResult.output ?? []);
}

async function compileTailwindCss() {
  // Setting Vite's root to the copied feature keeps Tailwind's automatic
  // candidate discovery inside Stoicheia. DataTeX classes cannot enter this
  // stylesheet, and unrelated UI changes cannot make the output stale.
  const result = await viteBuild({
    root: featureRoot,
    configFile: false,
    envFile: false,
    appType: "custom",
    mode: "production",
    logLevel: "silent",
    plugins: [
      tailwindcss({
        // Stable, readable output is intentional: the checked-in stylesheet
        // is audited after compilation and minified by the application build.
        optimize: false,
      }),
    ],
    build: {
      write: false,
      emptyOutDir: false,
      minify: false,
      cssMinify: false,
      modulePreload: false,
      rollupOptions: {
        input: sourcePath,
      },
    },
  });

  const cssAssets = normalizeBuildOutputs(result).filter(
    (output) => output.type === "asset" && output.fileName.endsWith(".css"),
  );

  if (cssAssets.length !== 1) {
    throw new Error(
      `Expected one compiled CSS asset, received ${cssAssets.length}.`,
    );
  }

  return String(cssAssets[0].source);
}

async function readExistingOutput() {
  try {
    return await fs.readFile(outputPath, "utf8");
  } catch (error) {
    if (error?.code === "ENOENT") {
      return null;
    }
    throw error;
  }
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const compiledCss = await compileTailwindCss();
  const scopedCss = scopeCss(compiledCss, {
    from: path.relative(repositoryRoot, sourcePath),
  });
  const generatedCss = `${generatedHeader}${scopedCss}`;
  const audit = auditCss(generatedCss, {
    from: path.relative(repositoryRoot, outputPath),
  });

  if (
    audit.leaksBeforeTransform.length > 0 ||
    audit.documentAnchors.length > 0 ||
    audit.globalNamespaceLeaks.length > 0
  ) {
    throw new Error(
      `Scoped output audit found ${audit.leaksBeforeTransform.length} selector leaks, ${audit.documentAnchors.length} document-root anchors, and ${audit.globalNamespaceLeaks.length} global namespace leaks.`,
    );
  }

  const namespaceSummary =
    `${audit.namespacedGlobals.tailwindCustomProperties.length} Tailwind custom properties; ` +
    `${audit.namespacedGlobals.cascadeLayers.length} cascade layers`;

  if (options.check) {
    const existing = await readExistingOutput();
    if (existing !== generatedCss) {
      throw new Error(
        `Generated stylesheet is missing or stale: ${path.relative(repositoryRoot, outputPath)}`,
      );
    }

    process.stdout.write(
      [
        `Stoicheia embedded CSS is current (${Buffer.byteLength(generatedCss)} bytes).`,
        `${audit.styleRuleCount} scoped rules; ${audit.keyframeStepCount} keyframe steps; 0 selector leaks.`,
        `${namespaceSummary}; 0 global namespace leaks.`,
        "",
      ].join("\n"),
    );
    return;
  }

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generatedCss, "utf8");
  process.stdout.write(
    [
      `Wrote ${path.relative(repositoryRoot, outputPath)} (${Buffer.byteLength(generatedCss)} bytes).`,
      `${audit.styleRuleCount} scoped rules; ${audit.keyframeStepCount} keyframe steps; 0 selector leaks.`,
      `${namespaceSummary}; 0 global namespace leaks.`,
      "",
    ].join("\n"),
  );
}

main().catch((error) => {
  process.stderr.write(`Stoicheia CSS build failed: ${error.message}\n`);
  process.exitCode = 1;
});
